extension TilesCLI.Operation {
    var helpUsage: String {
        let project = "--project PROJECT.cut [--source-id ID]"
        let input = "(SCAN.json | PROJECT.cut) [--source-id ID]"
        let edit = "(--out-project FILE | --in-place)"
        let feed = project + " --feed-id ID"
        let range = "[--from TIME --to TIME]"
        let picks = "(--all | --feed-id ID [--feed-id ID ...])"
        let scanOptions = "[--backend auto|cpu-only|gpu-required] [--sampling adaptive|every-frame|sparse] [--feed-layout auto|COLSxROWS] [--gallery-grid COLSxROWS]"
        let counts = "[--expected-feeds COUNT] [--max-visible-tiles COUNT]"
        let planOptions = "[--from TIME --to TIME] [--on-uncertain stop|blank] [--no-meeting-mix] [--no-isos] [--size WIDTHxHEIGHT] [--frame-rate RATE] [--fit fit|fill] [--gap-color COLOR] [--camera-off keep|blank]"
        let progress = "[--progress none|stderr|jsonl]"
        switch self {
        case .scan: return "MEDIA [--output SCAN.json] \(scanOptions) \(counts) [--include-scenes] [--no-sidecar] [--resume-file SCAN.json] \(progress)"
        case .inspect: return "\(input) [--clock source] [--at TIME | --issues | --layout-changes] \(range) [--rule JSON]"
        case .preview: return "\(input) [--clock source] (--at TIME | --issue-id ID) --output PNG"
        case .accept: return "\(project) (--scan SCAN.json \(counts) | --expected-feeds COUNT [--max-visible-tiles COUNT] | --max-visible-tiles COUNT | --clear-count-hints [--scan SCAN.json]) \(edit)"
        case .link: return "\(project) --tile-id ID (--feed-id ID | --clear) \(range) \(edit)"
        case .listFeeds: return input
        case .inspectFeed: return "\(input) --feed-id ID"
        case .addFeed: return "--project PROJECT.cut [--name NAME] \(edit)"
        case .renameFeed: return "\(feed) --name NAME \(edit)"
        case .micFeed: return "\(feed) (--mic-id ID [--audio-stream-index INDEX] | --clear) \(edit)"
        case .voiceFeed: return "\(feed) (--attachment-id ID --speaker-id ID | --clear) \(edit)"
        case .preferFeed: return "\(feed) (--tile-id ID | --clear) \(range) \(edit)"
        case .mergeFeeds: return "\(feed) --into-feed-id ID \(edit)"
        case .splitFeed: return "\(feed) --tile-id ID [--name NAME] \(range) \(edit)"
        case .treatFeed: return "\(feed) --treatment none|blur|cover|remove [--color HEX] \(edit)"
        case .confirmFeed: return "\(feed) \(range) \(edit)"
        case .planAngles: return "\(project) \(picks) --output PLAN.json \(planOptions)"
        case .renderAngles: return "(--plan PLAN.json | \(project) \(picks)) --output DIRECTORY [--resume] \(progress)"
        case .verifyAngles: return "DIRECTORY"
        case .exportISOs: return "(MEDIA | PROJECT.cut) --output DIRECTORY [--dry-run] [--resume] \(counts) \(scanOptions) \(planOptions) \(progress)"
        case .useAngles: return "\(project) \(picks) [--clip-id ID] \(edit)"
        case .proposeSwitches: return "--project PROJECT.cut [--attachment-id ID] [--minimum-hold TIME] [--voice-angle SPEAKER_ID=ANGLE_ID ...]"
        case .reconcile: return "\(project) --scan SCAN.json [--apply --review TOKEN \(edit)]"
        case .correctGrid: return "\(project) --from TIME --to TIME --grid COLSxROWS \(edit)"
        case .setLayout: return "\(project) (--clip-id ID | --occurrence-id ID | --group) --layout LAYOUT [--feed-id ID ...] [--slot JSON ...] [--compact] \(range) \(edit)"
        case .listLayouts: return "\(project) [--clip-id ID]"
        case .addBox, .setBox: return "\(project) \(self == .addBox ? "[--tile-id ID]" : "--tile-id ID") --from TIME --to TIME --bounds X,Y,W,H \(edit)"
        case .splitTile: return "\(project) --tile-id ID --at TIME [--new-tile-id ID] \(edit)"
        case .screenShare: return "\(project) --tile-id ID \(range) \(edit)"
        }
    }

    var helpExample: String {
        switch self {
        case .scan: return "meeting.mov --sampling every-frame --output meeting.json"
        case .inspect: return "reviewed.cut --issues"
        case .preview: return "meeting.json --at 00:32:10 --output gallery.png"
        case .accept: return "--project edit.cut --source-id meeting.mov --scan meeting.json --out-project reviewed.cut"
        case .link: return "reviewed.cut --tile-id tile-1 --feed-id alice --in-place"
        case .listFeeds: return "reviewed.cut"
        case .inspectFeed: return "reviewed.cut --feed-id alice"
        case .addFeed: return "meeting.cut --name Guest --in-place"
        case .renameFeed: return "reviewed.cut --feed-id alice --name Alice --in-place"
        case .micFeed: return "reviewed.cut --feed-id alice --mic-id alice-mic --in-place"
        case .voiceFeed: return "reviewed.cut --feed-id alice --attachment-id meeting --speaker-id speaker-1 --in-place"
        case .preferFeed: return "reviewed.cut --feed-id alice --tile-id tile-1 --in-place"
        case .mergeFeeds: return "reviewed.cut --feed-id feed-2 --into-feed-id alice --in-place"
        case .splitFeed: return "reviewed.cut --feed-id alice --tile-id tile-2 --name Bob --in-place"
        case .treatFeed: return "reviewed.cut --feed-id alice --treatment blur --in-place"
        case .confirmFeed: return "reviewed.cut --feed-id alice --in-place"
        case .planAngles: return "--project reviewed.cut --feed-id alice --output alice.plan.json"
        case .renderAngles: return "--plan alice.plan.json --output Alice-ISO"
        case .verifyAngles: return "Alice-ISO"
        case .exportISOs: return "meeting.mov --output ISOs --expected-feeds 40 --max-visible-tiles 25"
        case .useAngles: return "--project reviewed.cut --all --out-project angles.cut"
        case .proposeSwitches: return "--project angles.cut --attachment-id meeting --voice-angle speaker-1=alice"
        case .reconcile: return "reviewed.cut --scan rescanned.json"
        case .correctGrid: return "reviewed.cut --from 10 --to 20 --grid 5x5 --in-place"
        case .setLayout: return "reviewed.cut --clip-id clip-1 --layout solo --feed-id alice --in-place"
        case .listLayouts: return "reviewed.cut --clip-id clip-1"
        case .addBox: return "reviewed.cut --from 10 --to 20 --bounds 0,0,0.5,0.5 --in-place"
        case .setBox: return "reviewed.cut --tile-id tile-1 --from 10 --to 20 --bounds 0,0,0.5,0.5 --in-place"
        case .splitTile: return "reviewed.cut --tile-id tile-1 --at 15 --in-place"
        case .screenShare: return "reviewed.cut --tile-id tile-1 --in-place"
        }
    }
}
